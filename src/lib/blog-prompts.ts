export type ActivePromptResult = {
  text: string
  source: 'db' | 'fallback'
  meta: { id: string; version: number; label: string } | null
}

/**
 * 현재 active 시스템 프롬프트를 반환. DB 행이 없거나 조회 실패 시 코드 default fallback.
 * 호출자는 source 를 로깅해서 운영 시 어떤 경로가 쓰였는지 추적할 수 있음.
 */
export async function getActiveBlogPrompt(): Promise<ActivePromptResult> {
  try {
    const admin = createAdminClient()
    const { data, error } = await admin
      .from('jimscanner_blog_generation_prompts')
      .select('id, version, label, system_prompt')
      .eq('is_active', true)
      .maybeSingle()
    if (error || !data) {
      return { text: DEFAULT_BLOG_GENERATION_PROMPT, source: 'fallback', meta: null }
    }
    return {
      text: data.system_prompt,
      source: 'db',
      meta: { id: data.id, version: data.version, label: data.label },
    }
  } catch {
    return { text: DEFAULT_BLOG_GENERATION_PROMPT, source: 'fallback', meta: null }
  }
}
