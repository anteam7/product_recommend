const DEFAULT = 0.108 // 불명확 시 보수적 기본(생활잡화 서브 대부분 10.8%)

// 상품명/카테고리 텍스트 → 수수료율. 구체 카테고리 우선, 미매칭 시 DEFAULT.
export function commissionRate(text) {
  const s = String(text || '')
  // ── 자동차 (구체 → 일반) ──
  if (/(차량|자동차|송풍구|카).{0,6}(방향제|디퓨저|퍼퓸)|방향제.{0,4}(차량|자동차)/.test(s)) return 0.078
  if (/후방카메라|블랙박스|하이패스|내비게이션|경보기|스마트키|카플레이/.test(s)) return 0.078
  if (/타이어|휠커버|휠악세|알로이휠/.test(s)) return 0.096
  if (/오토바이|바이크/.test(s)) return 0.076
  if (/자동차|차량용?|카시트|핸들커버|트렁크|와이퍼|햇빛가리개|성에|주차|차박(?!.*테이블)|카매트|썬바이저/.test(s)) return 0.10
  // ── 뷰티 ──
  if (/스킨|로션|에센스|앰플|세럼|크림(?!.*치약)|클렌징|마스크팩|선크림|선블록|화장품|뷰티|샴푸|바디워시|틴트|쿠션팩트/.test(s)) return 0.096
  // ── 식품/영양 ──
  if (/영양제|비타민|유산균|오메가|콜라겐/.test(s)) return 0.076
  if (/라면|면류/.test(s)) return 0.109
  if (/식품|간식(?!.*(강아지|고양이|반려|애견))|음료|과자|커피|생수|건조|즉석|소스|양념/.test(s)) return 0.106
  // ── 반려 (간식/배변 등 포함, 식품보다 우선 처리 위해 위 식품에서 반려 제외) ──
  if (/반려|강아지|고양이|애견|애묘|펫|노즈워크|배변|사료|하네스|리드줄|캣타워|스크래처|이발기.*(반려|애견|강아지)/.test(s)) return 0.108
  // ── 문구/사무 ──
  if (/문구|사무|볼펜|연필|펜꽂이|필기|파일|바인더|테이프|노트|다이어리|스탬프|클립|포스트잇/.test(s)) return 0.108
  // ── 완구 ──
  if (/드론|쿼드콥터/.test(s)) return 0.078
  // ── 나머지 생활잡화 서브카테고리(전부 10.8%) ── 이미 DEFAULT지만 명시
  // 수납/정리, 청소/세탁/욕실, 주방, 공구/철물, 조명, 캠핑(스포츠레저), 가구 → 0.108
  return DEFAULT
}
